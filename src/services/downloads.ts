import type { Order } from "./types";
export async function downloadFreePreview(imageUrl: string, order: Order) {
  const image = new Image();
  image.crossOrigin = "anonymous";
  image.src = imageUrl;
  await image.decode();
  const canvas = document.createElement("canvas");
  canvas.width = 360;
  canvas.height = 480;
  const ctx = canvas.getContext("2d");
  if (!ctx) throw new Error("Download unavailable");
  ctx.drawImage(image, 0, 0, 360, 480);
  ctx.save();
  ctx.translate(180, 220);
  ctx.rotate(-Math.PI / 7);
  ctx.fillStyle = "rgba(15,76,92,.75)";
  ctx.fillRect(-200, -28, 400, 60);
  ctx.font = "bold 19px sans-serif";
  ctx.fillStyle = "white";
  ctx.textAlign = "center";
  ctx.fillText("FREE PREVIEW · WATERMARK", 0, 10);
  ctx.restore();
  ctx.fillStyle = "rgba(255,249,240,.94)";
  ctx.fillRect(0, 395, 360, 85);
  ctx.fillStyle = "#0F4C5C";
  ctx.font = "22px Georgia";
  ctx.textAlign = "center";
  ctx.fillText(`${order.details.host} & ${order.details.partner}`, 180, 430);
  ctx.font = "13px sans-serif";
  ctx.fillText(order.details.events[0]?.date ?? "", 180, 460);
  const blob = await new Promise<Blob | null>((resolve) => canvas.toBlob(resolve, "image/png"));
  if (!blob) throw new Error("Download unavailable");
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${order.id}-free-watermarked-preview.png`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
